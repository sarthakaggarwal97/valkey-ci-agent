def test_git_runner_profiles_preserve_subprocess_semantics(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    calls: list[tuple[list[str], dict[str, object]]] = []

    def fake_run(cmd: list[str], **kwargs: object) -> subprocess.CompletedProcess[str]:
        calls.append((cmd, kwargs))
        return subprocess.CompletedProcess(cmd, 0, stdout="ok", stderr="")

    monkeypatch.setattr(main.subprocess, "run", fake_run)
    assert main._run_git("/repo", "status") is None
    assert calls.pop(0) == (
        ["git", "status"],
        {
            "cwd": "/repo",
            "capture_output": True,
            "text": True,
            "env": None,
        },
    )

    monkeypatch.setattr(cherry_pick_module.subprocess, "run", fake_run)
    cherry_result = cherry_pick_module._run_git("/repo", "status", check=False)
    assert cherry_result.stdout == "ok"
    assert calls.pop(0) == (
        ["git", "status"],
        {
            "cwd": "/repo",
            "capture_output": True,
            "text": True,
            "errors": "replace",
            "check": False,
        },
    )

    sweep_result = sweep_apply._run_captured_git(
        "/repo",
        "status",
        check=False,
        run_process=fake_run,
    )
    assert sweep_result.stdout == "ok"
    assert calls.pop(0) == (
        ["git", "status"],
        {
            "cwd": "/repo",
            "capture_output": True,
            "text": True,
        },
    )


def test_git_runner_profiles_preserve_failure_handling(
    monkeypatch: pytest.MonkeyPatch,
    caplog: pytest.LogCaptureFixture,
) -> None:
    def fail(cmd: list[str], **_kwargs: object) -> subprocess.CompletedProcess[str]:
        return subprocess.CompletedProcess(
            ["completed-process-command"],
            7,
            stdout="stdout",
            stderr="stderr",
        )

    monkeypatch.setattr(cherry_pick_module.subprocess, "run", fail)
    with pytest.raises(subprocess.CalledProcessError) as cherry_error:
        cherry_pick_module._run_git("/repo", "status")
    assert cherry_error.value.cmd == ["git", "status"]
    assert cherry_error.value.output == "stdout"
    assert cherry_error.value.stderr == "stderr"

    monkeypatch.setattr(main.subprocess, "run", fail)
    with caplog.at_level(logging.ERROR, logger="scripts.backport.main"):
        with pytest.raises(subprocess.CalledProcessError) as pipeline_error:
            main._run_git("/repo", "status")
    assert pipeline_error.value.cmd == ["completed-process-command"]
    assert "git status failed (rc=7)" in caplog.text


