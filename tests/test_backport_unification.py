@pytest.mark.parametrize(
    ("materialize_in_retry", "expected_order"),
    [
        (False, ["get", "retry-return", "iterate"]),
        (True, ["get", "iterate", "retry-return"]),
    ],
)
def test_pr_lookup_preserves_materialization_timing(
    monkeypatch: pytest.MonkeyPatch,
    materialize_in_retry: bool,
    expected_order: list[str],
) -> None:
    events: list[str] = []
    pull = SimpleNamespace(
        head=SimpleNamespace(repo=SimpleNamespace(full_name="fork/repo")),
    )

    class Pulls:
        def __iter__(self):
            events.append("iterate")
            return iter([pull])

    class Repo:
        def get_pulls(self, *, state: str, head: str) -> Pulls:
            assert (state, head) == ("open", "fork:agent/backport/sweep/8.1")
            events.append("get")
            return Pulls()

    def retry(operation, *, retries: int, description: str):
        assert (retries, description) == (2, "list PRs")
        result = operation()
        events.append("retry-return")
        return result

    monkeypatch.setattr(pr_creator, "retry_github_call", retry)

    assert find_pull_by_head(
        Repo(),
        base_repo="upstream/repo",
        push_repo="fork/repo",
        branch_name="agent/backport/sweep/8.1",
        state="open",
        retries=2,
        retry_description="list PRs",
        materialize_in_retry=materialize_in_retry,
    ) is pull
    assert events == expected_order


def test_sweep_pr_lookup_preserves_its_retry_binding(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    events: list[str] = []
    pull = SimpleNamespace(
        head=SimpleNamespace(repo=SimpleNamespace(full_name="fork/repo")),
    )

    class Repo:
        def get_pulls(self, *, state: str, head: str) -> list[object]:
            assert (state, head) == ("open", "fork:agent/backport/sweep/8.1")
            return [pull]

    class GitHub:
        def get_repo(self, name: str) -> Repo:
            assert name == "upstream/repo"
            return Repo()

    def sweep_retry(operation, *, retries: int, description: str):
        events.append(f"{retries}:{description}")
        return operation()

    def wrong_retry(*_args: object, **_kwargs: object) -> None:
        pytest.fail("sweep lookup used pr_creator.retry_github_call")

    monkeypatch.setattr(sweep_prs, "retry_github_call", sweep_retry)
    monkeypatch.setattr(pr_creator, "retry_github_call", wrong_retry)

    assert sweep_prs.find_existing_pr(
        GitHub(),
        "upstream/repo",
        "fork/repo",
        "agent/backport/sweep/8.1",
    ) is pull
    assert events == ["2:get upstream/repo", "2:list PRs"]


