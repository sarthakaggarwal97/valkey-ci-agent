@pytest.mark.parametrize(
    ("query", "require_id"),
    [
        (sweep._project_items_query("organization"), False),
        (mark_done._project_query("organization"), True),
    ],
)
def test_shared_project_loader_preserves_pagination(
    query: str,
    require_id: bool,
) -> None:
    calls: list[dict[str, object]] = []
    responses = [
        {
            "organization": {
                "projectV2": {
                    "id": "PVT_1",
                    "fields": {"nodes": [{"id": "field"}]},
                    "items": {
                        "nodes": [{"id": "first"}],
                        "pageInfo": {
                            "hasNextPage": True,
                            "endCursor": "cursor-1",
                        },
                    },
                }
            }
        },
        {
            "organization": {
                "projectV2": {
                    "id": "PVT_1",
                    "fields": {"nodes": []},
                    "items": {
                        "nodes": [{"id": "second"}],
                        "pageInfo": {
                            "hasNextPage": False,
                            "endCursor": None,
                        },
                    },
                }
            }
        },
    ]

    class FakeClient:
        def execute(
            self,
            _query: str,
            variables: dict[str, object],
        ) -> dict[str, object]:
            calls.append(variables)
            return responses.pop(0)

    project = load_project_v2(
        FakeClient(),
        project_owner="valkey-io",
        project_number=14,
        project_owner_type="organization",
        query=query,
        require_id=require_id,
    )

    assert [item["id"] for item in project.items] == ["first", "second"]
    assert project.id == "PVT_1"
    assert project.fields == [{"id": "field"}]
    assert calls == [
        {"owner": "valkey-io", "number": 14, "cursor": None},
        {"owner": "valkey-io", "number": 14, "cursor": "cursor-1"},
    ]


